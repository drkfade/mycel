export function build() {
  fs.mkdirSync(path.dirname(aiPagePath), { recursive: true });
  let changed = false;
  const jsNext = renderAiLessonsJs();
  const jsPrev = fs.existsSync(aiLessonsJsPath) ? fs.readFileSync(aiLessonsJsPath, "utf8") : "";
  if (jsNext !== jsPrev) { fs.writeFileSync(aiLessonsJsPath, jsNext); changed = true; }
  const next = render();
  const prev = fs.existsSync(aiPagePath) ? fs.readFileSync(aiPagePath, "utf8") : "";
  if (next !== prev) { fs.writeFileSync(aiPagePath, next); changed = true; }
  return changed;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  console.log(build() ? `wrote ${path.relative(mycelDir, aiPagePath)} + ai-lessons.js` : "AI track page already up to date");
}
