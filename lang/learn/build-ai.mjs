// The optional "train it on your own data" part of a lesson: a section after the exercise, with its own solution.
function ownDataHtml(l) {
  const o = l.ownData;
  const sol = readSample(o.file);
  return `<h3 class="own-data" id="${l.id}-own-data">Train it on your own data</h3>
${o.text}
<p class="task"><b>Your turn.</b> ${o.task}</p>
<details class="solution"><summary>Show the solution</summary>
<p class="lesson-meta">Save as <code>${o.file}.myc</code> &middot; run with <code>mycel run --allow-read=. ${o.file}.myc</code> from the folder that holds <code>${o.data}</code></p>
<pre class="static"><code>${esc(sol)}</code></pre>
<p class="lesson-meta">Output</p>
<pre class="static"><code>${esc(o.out)}</code></pre>
</details>`;
}

export function renderAiLessonsJs() {
  const payload = {
    units,
    lessons: lessons.map((l) => ({
      id: l.id,
      unit: l.unit,
      points: l.points,
      browserRunnable: !!l.browserRunnable,
      file: l.file,
      title: l.title,
      flags: l.flags || "",
      stdin: l.stdin || "",
      code: readSample(l.file),
      out: l.out,
      solution: readSample(l.exercise.file),
      expectedOut: l.exercise.out,
      exerciseFile: l.exercise.file,
      exerciseFlags: l.exercise.flags || l.flags || "",
      exerciseStdin: l.exercise.stdin || "",
      hints: l.hints || [],
      commonMistakes: l.commonMistakes || [],
    })),
  };
  return `// Generated by lang/learn/build-ai.mjs from lang/learn/ai-course.mjs and samples/ai/*.myc; do not edit.\n(function (root) {\n"use strict";\nconst DATA = ${JSON.stringify(payload, null, 2)};\nroot.MYCEL_AI_UNITS = DATA.units;\nroot.MYCEL_AI_LESSONS = DATA.lessons;\n})(typeof self !== "undefined" ? self : globalThis);\n`;
}

