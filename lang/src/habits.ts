/** Operator sequences the lexer splits: `++`, `--`, `:=`, `===`, `!==`. Keyed by the two tokens. */
export function sequenceHabit(a: string, b: string): string | undefined {
  if (a === "+" && b === "+") return "`x++` — Mycel writes `x += 1`";
  if (a === "-" && b === "-") return "`x--` — Mycel writes `x -= 1`";
  if (a === ":" && b === "=") return "`:=` is Go — Mycel writes `let x = value` (or `x = value` to change a `var`)";
  if (a === "==" && b === "=") return "`===` is JavaScript — Mycel's `==` already compares values: write `==`";
  if (a === "!=" && b === "=") return "`!==` is JavaScript — write `!=`";
  if (a === ":" && b === ":") return "`::` is Rust/C++ — Mycel writes `.` (`String.from`, `Color.Red`)";
  if (a === ".." && b === "<") return "`..<` is Swift — Mycel's `0..n` already excludes the end (`0..=n` includes it)";
  return undefined;
}

